package com.example.orders.migration;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Redirects old webapp URLs ({@code /camunda/**}) to the new application path ({@code /operaton/**} by
 * default) - for the release in which decision D6 moves the webapps from {@code /camunda} to Operaton's
 * default path. Opt-in: {@code orders.migration.legacy-webapp-redirect.enabled=true}.
 *
 * <ul>
 *   <li>Only {@code GET}/{@code HEAD} are redirected (302 by default; switch to 301 once stable). Other
 *       methods (API calls with CSRF tokens, form posts) are passed through and will 404 - clients have
 *       to be changed, a redirect would silently drop request bodies.</li>
 *   <li>The query string is preserved. URL fragments ({@code #/process-instance/...} deep links of
 *       Cockpit/Tasklist) are never sent to the server; browsers re-apply them to the redirect target,
 *       so bookmarks keep working.</li>
 *   <li>Fails fast if the legacy path equals the current application path (redirect loop).</li>
 * </ul>
 *
 * <p>Also update reverse-proxy/ingress rules, WAF allow-lists, SSO redirect URIs, synthetic checks and
 * links generated by your code. Generic: no application-specific dependencies.
 */
public class LegacyWebappPathRedirectFilter extends OncePerRequestFilter {

  private final String legacyPath;
  private final String targetPath;
  private final int status;

  public LegacyWebappPathRedirectFilter(String legacyPath, String targetPath, int status) {
    this.legacyPath = normalize(legacyPath);
    this.targetPath = normalize(targetPath);
    if (this.legacyPath.isEmpty() || this.legacyPath.equals(this.targetPath)) {
      throw new IllegalStateException("Legacy webapp path '" + legacyPath + "' must differ from the application path '"
          + targetPath + "' (operaton.bpm.webapp.application-path) - otherwise the redirect would loop");
    }
    if (status != HttpServletResponse.SC_FOUND && status != HttpServletResponse.SC_MOVED_PERMANENTLY) {
      throw new IllegalArgumentException("status must be 302 or 301, was " + status);
    }
    this.status = status;
  }

  public LegacyWebappPathRedirectFilter(String legacyPath, String targetPath) {
    this(legacyPath, targetPath, HttpServletResponse.SC_FOUND);
  }

  @Override
  protected boolean shouldNotFilter(HttpServletRequest request) {
    String method = request.getMethod();
    if (!"GET".equals(method) && !"HEAD".equals(method)) {
      return true;
    }
    String path = pathWithinApplication(request);
    return !(path.equals(legacyPath) || path.startsWith(legacyPath + "/"));
  }

  @Override
  protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain chain)
      throws ServletException, IOException {
    String rest = pathWithinApplication(request).substring(legacyPath.length());
    String query = request.getQueryString() == null ? "" : "?" + request.getQueryString();
    response.setStatus(status);
    response.setHeader("Location", request.getContextPath() + targetPath + rest + query);
  }

  private static String pathWithinApplication(HttpServletRequest request) {
    String uri = request.getRequestURI();
    String contextPath = request.getContextPath();
    return contextPath != null && !contextPath.isEmpty() && uri.startsWith(contextPath)
        ? uri.substring(contextPath.length())
        : uri;
  }

  private static String normalize(String path) {
    if (path == null) {
      return "";
    }
    String p = path.trim();
    if (!p.isEmpty() && !p.startsWith("/")) {
      p = "/" + p;
    }
    while (p.endsWith("/")) {
      p = p.substring(0, p.length() - 1);
    }
    return p;
  }

  public String getLegacyPath() {
    return legacyPath;
  }

  public String getTargetPath() {
    return targetPath;
  }
}
